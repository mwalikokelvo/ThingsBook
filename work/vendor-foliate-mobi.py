"""Vendors foliate-js's MOBI/KF8 parser as a classic script for ThingsBook.

usage: python work/vendor-foliate-mobi.py <path to a foliate-js checkout>

Writes outputs/ThingsBook/vendor/foliate-mobi.js (global ThingsFoliateMobi = {MOBI, isMOBI})
and outputs/ThingsBook/vendor/FOLIATE-LICENSE.txt. Source: https://github.com/johnfactotum/foliate-js
(MIT). mobi.js has no imports; the only changes are mechanical:
  1. `export` keywords removed and the module wrapped in an IIFE (the app loads classic scripts);
  2. each section object also exposes `loadText()`, the section's markup before foliate swaps
     resources for blob: URLs, which ThingsBook's converter needs to build a self-contained EPUB.
"""
import re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / 'outputs/ThingsBook/vendor'


def main(checkout):
    checkout = Path(checkout).resolve()
    source = (checkout / 'mobi.js').read_text(encoding='utf-8')
    commit = subprocess.run(['git', '-C', str(checkout), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()

    if re.search(r'^\s*import\s', source, re.M):
        raise SystemExit('mobi.js now has imports; review before vendoring.')
    exports = re.findall(r'^export (?:const|class|function|async function) (\w+)', source, re.M)
    if sorted(exports) != ['MOBI', 'isMOBI']:
        raise SystemExit(f'Unexpected exports {exports}; review before vendoring.')
    body = re.sub(r'^export (?=const|class|function|async function)', '', source, flags=re.M)

    patch = 'createDocument: () => this.createDocument(section),'
    if body.count(patch) != 2:
        raise SystemExit('Section objects changed shape; review the loadText patch.')
    body = body.replace(patch, patch + ' loadText: () => this.loadText(section), // ThingsBook patch')

    header = f"""// foliate-js mobi.js — MOBI 6 / KF8 (AZW3) parser.
// Source: https://github.com/johnfactotum/foliate-js/blob/{commit}/mobi.js
// License: MIT (see FOLIATE-LICENSE.txt). Generated by work/vendor-foliate-mobi.py; do not edit by hand.
// Local changes: classic-script wrapper (global ThingsFoliateMobi), and sections expose loadText().
"""
    out = header + "const ThingsFoliateMobi = (() => {\n'use strict';\n" + body + "\nreturn Object.freeze({ MOBI, isMOBI });\n})();\nif (typeof module !== 'undefined') module.exports = ThingsFoliateMobi;\n"
    (VENDOR / 'foliate-mobi.js').write_text(out, encoding='utf-8')
    (VENDOR / 'FOLIATE-LICENSE.txt').write_text((checkout / 'LICENSE').read_text(encoding='utf-8'), encoding='utf-8')
    print(f'vendored foliate-js {commit[:12]} mobi.js ({len(out)} bytes)')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
