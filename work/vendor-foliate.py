"""Vendors foliate-js's MOBI/KF8 and FB2 parsers as classic scripts for ThingsBook.

usage: python work/vendor-foliate.py <path to a foliate-js checkout>

Writes outputs/ThingsBook/vendor/foliate-mobi.js (global ThingsFoliateMobi = {MOBI, isMOBI}),
outputs/ThingsBook/vendor/foliate-fb2.js (global ThingsFoliateFB2 = {makeFB2, STYLE_TEXT}) and
outputs/ThingsBook/vendor/FOLIATE-LICENSE.txt. Source: https://github.com/johnfactotum/foliate-js
(MIT). Neither module has imports; the only changes are mechanical and checked:
  1. `export` keywords removed and each module wrapped in an IIFE (the app loads classic scripts);
  2. mobi.js: each section object also exposes `loadText()`, the section's markup before foliate swaps
     resources for blob: URLs, which ThingsBook's converter needs to build a self-contained EPUB;
  3. fb2.js: the default stylesheet text is kept as STYLE_TEXT so it can be written into the EPUB.
"""
import re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / 'outputs/ThingsBook/vendor'


def wrap(name, source, commit, exports, local_changes):
    if re.search(r'^\s*import\s', source, re.M):
        raise SystemExit(f'{name} now has imports; review before vendoring.')
    found = re.findall(r'^export (?:const|class|function|async function) (\w+)', source, re.M)
    if sorted(found) != sorted(exports):
        raise SystemExit(f'{name}: unexpected exports {found}; review before vendoring.')
    return re.sub(r'^export (?=const|class|function|async function)', '', source, flags=re.M), f"""// foliate-js {name}.
// Source: https://github.com/johnfactotum/foliate-js/blob/{commit}/{name}
// License: MIT (see FOLIATE-LICENSE.txt). Generated by work/vendor-foliate.py; do not edit by hand.
// Local changes: classic-script wrapper{local_changes}.
"""


def main(checkout):
    checkout = Path(checkout).resolve()
    commit = subprocess.run(['git', '-C', str(checkout), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()

    body, header = wrap('mobi.js', (checkout / 'mobi.js').read_text(encoding='utf-8'), commit, ['MOBI', 'isMOBI'], ' (global ThingsFoliateMobi), and sections expose loadText()')
    patch = 'createDocument: () => this.createDocument(section),'
    if body.count(patch) != 2:
        raise SystemExit('mobi.js section objects changed shape; review the loadText patch.')
    body = body.replace(patch, patch + ' loadText: () => this.loadText(section), // ThingsBook patch')
    out = header + "const ThingsFoliateMobi = (() => {\n'use strict';\n" + body + "\nreturn Object.freeze({ MOBI, isMOBI });\n})();\nif (typeof module !== 'undefined') module.exports = ThingsFoliateMobi;\n"
    (VENDOR / 'foliate-mobi.js').write_text(out, encoding='utf-8')

    body, header = wrap('fb2.js', (checkout / 'fb2.js').read_text(encoding='utf-8'), commit, ['makeFB2'], ' (global ThingsFoliateFB2), and the stylesheet text is kept as STYLE_TEXT')
    opening, closing = 'const style = URL.createObjectURL(new Blob([`', "`], { type: 'text/css' }))"
    if body.count(opening) != 1 or body.count(closing) != 1:
        raise SystemExit('fb2.js stylesheet changed shape; review the STYLE_TEXT patch.')
    body = body.replace(opening, 'const STYLE_TEXT = `').replace(closing, "`\nconst style = URL.createObjectURL(new Blob([STYLE_TEXT], { type: 'text/css' })) // ThingsBook patch")
    out = header + "const ThingsFoliateFB2 = (() => {\n'use strict';\n" + body + "\nreturn Object.freeze({ makeFB2, STYLE_TEXT });\n})();\nif (typeof module !== 'undefined') module.exports = ThingsFoliateFB2;\n"
    (VENDOR / 'foliate-fb2.js').write_text(out, encoding='utf-8')

    (VENDOR / 'FOLIATE-LICENSE.txt').write_text((checkout / 'LICENSE').read_text(encoding='utf-8'), encoding='utf-8')
    print(f'vendored foliate-js {commit[:12]}: mobi.js, fb2.js')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
